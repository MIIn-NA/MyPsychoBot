"""НАСТЯ Рекомендации и правила их выбора"""

import re

class KnowledgeBase:
    def __init__(self):
        # Базовые рекомендации для каждого класса
        self.base_recommendations = {
            0: "Отлично! Вы в ресурсном состоянии. Поддерживайте режим сна и физическую активность.",
            1: "Похоже, вы испытываете стресс. Попробуйте дыхательное упражнение 4-7-8: вдох на 4 секунды, задержка на 7, выдох на 8.",
            2: "Я замечаю признаки тревоги. Попробуйте технику заземления 5-4-3-2-1: назовите 5 предметов вокруг, 4 звука, 3 ощущения, 2 запаха и 1 вкус."
        }

        # Контекстные правила (если в тексте есть определенные слова)
        # Формат: "ключевое_слово": {класс: "рекомендация"}
        self.context_rules = {
            "экзамен": {
                1: "Упоминание экзамена. Составьте четкий план подготовки, разбейте материал на небольшие блоки и начните с самого простого.",
                2: "Тревога из-за экзамена. Попробуйте выписать все свои страхи на бумагу, а затем составьте план действий."
            },
            "сон": {
                2: "Проблемы со сном. Попробуйте за час до сна убрать телефон и выпить травяной чай."
            },
            "устал": {
                1: "Вы чувствуете усталость. Сделайте перерыв на 15 минут, отвлекитесь от учебы и выпейте воды."
            }
        }

    def get_recommendation(self, text, predicted_class):
        """
        Принимает текст и предсказанный класс (0, 1 или 2).
        Возвращает строку с рекомендацией.
        """
        # Приводим текст к нижнему регистру для удобного поиска
        text_lower = text.lower()

        # 1. Проверяем контекстные правила
        for keyword, rules in self.context_rules.items():
            # Если ключевое слово есть в тексте
            if re.search(r'\b' + keyword + r'\b', text_lower):
                # Если для этого класса есть специфичное правило
                if predicted_class in rules:
                    return rules[predicted_class]

        # 2. Если контекстных правил не сработало, выдаем базовую рекомендацию
        return self.base_recommendations.get(predicted_class, "Продолжайте следить за своим состоянием.")

# --- Блок для проверки ---
# Этот код выполнится только если запустить файл напрямую
if __name__ == "__main__":
    kb = KnowledgeBase()
    
    # Тест 1: Стресс + экзамен
    print(kb.get_recommendation("Я очень переживаю из-за экзамена", 1))
    
    # Тест 2: Тревога + сон
    print(kb.get_recommendation("Я не могу уснуть уже 3 часа", 2))
    
    # Тест 3: Просто норма
    print(kb.get_recommendation("Сегодня хороший день", 0))